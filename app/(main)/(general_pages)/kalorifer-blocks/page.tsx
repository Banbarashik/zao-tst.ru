/* Формулы расчета многорядного блока */
function MultiRowBlockFormulas() {
  return (
    <>
      {/* Методика интегрального расчета блоков по методу NTU */}
      <Heading
        lvl={4}
        text="Методика интегрального расчета блоков по методу NTU"
        className="text-black"
      />

      <ol className="space-y-4">
        <li>
          <p>
            Шаг 1. Тепловая способность воздушного и водяного потоков (W, Вт/°C)
          </p>
          <p>
            Определяет количество тепловой энергии, необходимое для изменения
            температуры потока среды на 1 °C:
          </p>
          <ul>
            <li>• Воздушный поток: W_возд = (G_air / 3600) * 1006</li>
            <li>• Водяной поток: W_воды = (G_w_transit / 3600) * 4187</li>
          </ul>
          <p>
            Для проведения расчета выбирается наименьшее значение: W_min =
            W_возд
          </p>
          <p>
            На основании полученных величин вычисляется безразмерное отношение
            потоков: W_o = W_min / W_воды
          </p>
        </li>

        <li>
          <p>Шаг 2. Тепловой потенциал трубного пучка (NTU_block)</p>
          <p>
            Характеризует безразмерную тепловую способность всей площади
            поверхности нагрева установки относительно массового расхода
            воздуха:
          </p>
          <ul>
            <li>• NTU_block = (K_average * F_общ) / W_min</li>
          </ul>
          <p>
            Где: F_общ — суммарная площадь поверхности теплообмена всех четырех
            калориферов блока, м²; K_average — средний коэффициент теплопередачи
            оборудования, Вт/(м²·°C).
          </p>
        </li>

        <li>
          <p>Шаг 3. Итоговый тепловой КПД установки (E_block)</p>
          <p>
            Зависит от схемы движения теплоносителей и рассчитывается по
            интегральным зависимостям Кэйса-Босмана для неперемешивающихся сред:
          </p>
          <ul>
            <li>
              Перекрестноточная схема:{" "}
              <span className="block">
                E_block = 1 - exp((NTU_block^0.22 / W_o) * (exp(-W_o *
                NTU_block^0.78) - 1))
              </span>
            </li>
            <li>
              Последовательная прямоточная схема:{" "}
              <span className="block">
                E_block = (1 - exp(-NTU_block * (1 + W_o))) / (1 + W_o)
              </span>
            </li>
            <li>
              Последовательная противоточная схема:{" "}
              <span className="block">
                E_block = (1 - exp(-NTU_block * (1 - W_o))) / (1 - W_o *
                exp(-NTU_block * (1 - W_o)))
              </span>
            </li>
          </ul>
        </li>

        <li>
          <p>Шаг 4. Расчет финальных паспортных параметров</p>
          <li>
            • Общая тепловая мощность блока: Q = W_min * E_block * (T_вх_воды -
            t_вх_возд)
          </li>
          <li>
            • Температура воздуха на выходе: t_out_air = t_вх_возд + Q / W_возд
          </li>
          <li>• Температура обратной воды: T_out_w = T_вх_воды - Q / W_воды</li>
        </li>
      </ol>
    </>
  );
}

