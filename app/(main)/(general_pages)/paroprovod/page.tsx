function FractionInch({ value }: { value: string }) {
  const [whole, fraction] = value.split(" ");

  if (!fraction) return <>{whole}</>;

  const [num, den] = fraction.split("/");

  return (
    <>
      {whole}
      <sup>{num}</sup>/<sub>{den}</sub>
    </>
  );
}
